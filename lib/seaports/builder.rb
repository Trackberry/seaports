# frozen_string_literal: true

require "csv"
require "json"

require_relative "../seaports"
require_relative "alternate_names"

module Seaports
  # Rebuilds the shipped sea-port table from a published UN/LOCODE code list.
  #
  # The table is generated, not hand-maintained, and this is the only thing
  # that should ever write it — so a refresh is `rake seaports:refresh` against
  # a newer UNECE release rather than a diff someone edits by hand.
  #
  # UNECE's own distribution is a zip of headerless latin-1 CSVs, so the source
  # here is the datasets/un-locode mirror, which republishes the same list with
  # headers and UTF-8. It is a third party, which is why every refresh runs
  # through Seaports::Diff before anything ships.
  #
  # Nothing breaks if a release is skipped: a port missing from our copy falls
  # back to whatever the caller rendered before the table existed.
  class Builder
    SOURCE_URL = "https://raw.githubusercontent.com/datasets/un-locode/main/data/code-list.csv"
    DATAPACKAGE_URL = "https://raw.githubusercontent.com/datasets/un-locode/main/datapackage.json"

    HEADERS = %w[locode name lat lng subdivision principal_subdivision subdivision_path subdivision_source coordinate_source alternate_names].freeze

    # Where a port's position came from, best first. "unlocode" is UN/LOCODE's
    # own and always wins; a later regeneration may replace any of the others.
    COORDINATE_SOURCES = %w[unlocode override wpi wikidata].freeze
    FALLBACK_NAMES = %w[wpi wikidata].freeze

    # Reviewed subdivisions for ports neither UN/LOCODE nor the map places:
    # Valencia, Algeciras and Barcelona have no subdivision and no position.
    # Kept outside data/*.csv so it is not shipped in the gem; only its result
    # is.
    OVERRIDES_PATH = File.expand_path("../../data/sources/subdivision_overrides.csv", __dir__)

    # Reviewed positions for ports UN/LOCODE publishes none for: about a third
    # of the table, Valencia, Algeciras and Barcelona among them. Same rules as
    # the subdivision overrides, with one more: a position only ever fills a
    # gap. See Builder.coordinate_overrides.
    COORDINATE_OVERRIDES_PATH = File.expand_path("../../data/sources/coordinate_overrides.csv", __dir__)

    # Positions from two open datasets, for ports neither UN/LOCODE nor the
    # hand-written file places. Generated, then reviewed in the pull request
    # that changes them: the NGA World Port Index (public domain, refreshed
    # with `rake seaports:refresh_wpi`) and Wikidata (CC0, refreshed with
    # `rake seaports:refresh_wikidata`). Ranked in that order, after the
    # hand-written file; see Builder#coordinates_for.
    WPI_COORDINATES_PATH = File.expand_path("../../data/sources/coordinates_wpi.csv", __dir__)
    WIKIDATA_COORDINATES_PATH = File.expand_path("../../data/sources/coordinates_wikidata.csv", __dir__)

    # Other names for ports, best first: a hand-reviewed file, then the World
    # Port Index's alternate names (generated by `rake seaports:refresh_wpi`).
    # The parenthesized names in UN/LOCODE's own are added after both. See
    # Seaports::AlternateNames.
    ALTERNATE_NAMES_PATH = File.expand_path("../../data/sources/alternate_names.csv", __dir__)
    WPI_ALTERNATE_NAMES_PATH = File.expand_path("../../data/sources/alternate_names_wpi.csv", __dir__)
    # Names reviewed and refused for a port (locode, name, reason), whichever
    # source offers them: the wrong-place names that got past the index filter.
    REJECTED_ALTERNATE_NAMES_PATH = File.expand_path("../../data/sources/alternate_names_rejected.csv", __dir__)

    # The published list, straight off the network — or off disk, if what was
    # handed over is a path. Both, because a rebuild from an already-downloaded
    # release is how this is debugged, and it should not need a different
    # entry point. Kept separate from parsing so every other path through this
    # class can be tested with a string.
    def self.fetch(source = SOURCE_URL)
      return File.read(source) if File.exist?(source)

      require "open-uri"
      URI.parse(source).read
    end

    # Which UN/LOCODE edition the mirror is currently publishing, as UNECE
    # names it: "2024.2.0" upstream becomes "2024-2" here. Nil rather than a
    # guess if the mirror changes shape — a wrong release number is worse than
    # an absent one, because it would be believed.
    def self.published_release(source = DATAPACKAGE_URL)
      version = JSON.parse(fetch(source))["version"].to_s
      match = version.match(/\A(\d{4})\.(\d)/)
      match && "#{match[1]}-#{match[2]}"
    rescue StandardError
      nil
    end

    # The text of version.rb with a refresh's facts written in. The release is
    # replaced even when it is nil: keeping the previous one would label a new
    # table with an edition it did not come from.
    def self.stamp_version(content, version:, release:, refreshed_on:)
      content
        .sub(/VERSION = "[^"]*"/, %(VERSION = "#{version}"))
        .sub(/DATA_RELEASE = (?:"[^"]*"|nil)/, "DATA_RELEASE = #{release.inspect}")
        .sub(/DATA_REFRESHED_ON = "[^"]*"/, %(DATA_REFRESHED_ON = "#{refreshed_on}"))
    end

    # Reads OVERRIDES_PATH (or +path+) into { locode => ISO 3166-2 code }.
    #
    # The file is typed by people, so a blank cell, a malformed locode or a
    # port listed twice stops the build with the line to fix, rather than
    # crashing on a nil or letting the second row quietly win.
    def self.overrides(path = OVERRIDES_PATH)
      return {} unless File.exist?(path)

      CSV.foreach(path, headers: true).with_index(2).each_with_object({}) do |(row, line), overrides|
        locode = row["locode"].to_s.strip.upcase
        code = row["subdivision"].to_s.strip.upcase
        raise ArgumentError, "#{path}:#{line}: #{locode.inspect} is not a locode" unless locode.match?(/\A[A-Z]{2}[A-Z0-9]{3}\z/)
        raise ArgumentError, "#{path}:#{line}: #{locode} has no subdivision" if code.empty?
        raise ArgumentError, "#{path}:#{line}: #{locode} is listed twice" if overrides.key?(locode)

        overrides[locode] = code
      end
    end

    # Reads COORDINATE_OVERRIDES_PATH (or +path+) into { locode => [lat, lng] }.
    #
    # A position is typed by a person, so a malformed locode, a coordinate that
    # is not a number on the globe, a missing source or a port listed twice
    # stops the build with the line to fix. The source is required because a
    # position nobody can check is worse than none: a map would draw it.
    # Rounded to four places, as the UN/LOCODE positions are.
    def self.coordinate_overrides(path = COORDINATE_OVERRIDES_PATH)
      return {} unless File.exist?(path)

      CSV.foreach(path, headers: true).with_index(2).each_with_object({}) do |(row, line), overrides|
        locode = row["locode"].to_s.strip.upcase
        raise ArgumentError, "#{path}:#{line}: #{locode.inspect} is not a locode" unless locode.match?(/\A[A-Z]{2}[A-Z0-9]{3}\z/)
        raise ArgumentError, "#{path}:#{line}: #{locode} has no source" if row["source"].to_s.strip.empty?
        raise ArgumentError, "#{path}:#{line}: #{locode} is listed twice" if overrides.key?(locode)

        lat = Float(row["lat"].to_s.strip, exception: false)
        lng = Float(row["lng"].to_s.strip, exception: false)
        unless lat && lng && lat.between?(-90, 90) && lng.between?(-180, 180)
          raise ArgumentError, "#{path}:#{line}: #{locode} has no valid lat and lng"
        end

        overrides[locode] = [lat.round(4), lng.round(4)]
      end
    end

    # The generated position files, best first: [World Port Index, Wikidata],
    # each { locode => [lat, lng] }. Read by the same rules as the
    # hand-written file, source required, because a generated file is still
    # one a person reviews.
    def self.fallback_coordinates(paths = [WPI_COORDINATES_PATH, WIKIDATA_COORDINATES_PATH])
      paths.map { |path| coordinate_overrides(path) }
    end

    # The supplementary positions by source, best first: { "override" => {...},
    # "wpi" => {...}, "wikidata" => {...} }, each { locode => [lat, lng] }.
    def self.coordinate_layers
      wpi, wikidata = fallback_coordinates
      { "override" => coordinate_overrides, "wpi" => wpi, "wikidata" => wikidata }
    end

    # Every supplementary position the builder would use, one per port, in
    # precedence order: hand-written, then World Port Index, then Wikidata.
    def self.all_coordinates
      coordinate_layers.values.reverse.reduce({}, :merge)
    end

    # The alternate-name files, best first, each { locode => [names] }. Read by
    # the same rules, source required, because a generated file is still one a
    # person reviews.
    def self.alternate_name_layers(paths = [ALTERNATE_NAMES_PATH, WPI_ALTERNATE_NAMES_PATH])
      paths.map { |path| AlternateNames.read(path) }
    end

    # { locode => [names] } of REJECTED_ALTERNATE_NAMES_PATH (or +path+), read by
    # the same rules, with a reason in place of the source.
    def self.rejected_alternate_names(path = REJECTED_ALTERNATE_NAMES_PATH)
      AlternateNames.read(path, third: "reason")
    end

    # Writes the alternate names in +layers+ (see alternate_name_layers) into
    # the table at +path+, without a download: how a reviewed row reaches the
    # table between refreshes. Returns the locodes whose names changed.
    def self.apply_alternate_names(path = Seaports::TABLE_PATH, layers = alternate_name_layers, rejected = rejected_alternate_names)
      changed = []
      table = CSV.read(path, headers: true)
      candidates = table.map do |row|
        [row["locode"], row["name"], AlternateNames.for(locode: row["locode"], name: row["name"], located: !row["lat"].to_s.empty?,
          layers:, rejected:)]
      end
      names = AlternateNames.resolve(candidates)
      rows = table.map do |row|
        was = row["alternate_names"].to_s
        row["alternate_names"] = AlternateNames.dump(names.fetch(row["locode"], []))
        changed << row["locode"] if was != row["alternate_names"].to_s
        row.fields(*HEADERS)
      end
      CSV.open(path, "w") do |csv|
        csv << HEADERS
        rows.each { |row| csv << row }
      end
      changed
    end

    # Writes the supplementary positions in +layers+ (see coordinate_layers; a
    # flat { locode => [lat, lng] } counts as the "override" layer) into the
    # table at +path+, without a download: how a reviewed row reaches the table
    # between refreshes. A refresh gets the same result by itself, and also
    # places the port on the boundaries map, which this does not.
    #
    # A row the builder recorded as UN/LOCODE's own (coordinate_source
    # "unlocode") is never touched. Every other row takes the best layer's
    # position, or loses its position when no layer has one any more: it was
    # never UN/LOCODE's, so a row that left its source file leaves the table
    # too. Returns the locodes whose position changed.
    def self.apply_coordinates(path = Seaports::TABLE_PATH, layers = coordinate_layers)
      layers = { "override" => layers } if layers.values.first.is_a?(Array)
      changed = []
      rows = CSV.read(path, headers: true).map do |row|
        next row.fields if row["coordinate_source"] == "unlocode" || (row["coordinate_source"].nil? && !row["lat"].to_s.empty?)

        source, point = layers.lazy.filter_map { |name, points| [name, points[row["locode"]]] if points[row["locode"]] }.first
        was = [row["lat"].to_s, row["lng"].to_s]
        row["lat"], row["lng"] = point
        row["coordinate_source"] = point && source
        changed << row["locode"] if was != [row["lat"].to_s, row["lng"].to_s]
        row.fields
      end
      CSV.open(path, "w") do |csv|
        csv << HEADERS
        rows.each { |row| csv << row }
      end
      changed
    end

    # Where a port's subdivision comes from, best first:
    #
    # - +overrides+, { locode => code }, reviewed by a person;
    # - UN/LOCODE's own subdivision column;
    # - +boundaries+ (Seaports::Boundaries), the subdivision the port's
    #   coordinates fall in.
    #
    # Every code is checked against +subdivisions+, the ISO 3166-2 list (see
    # Seaports::Subdivisions), which also gives the principal subdivision
    # above it. Without that list the subdivision columns stay empty, which
    # keeps a test about something else from needing it.
    #
    # +coordinate_overrides+, { locode => [lat, lng] }, fills ports UN/LOCODE
    # has no position for, and never replaces one it has: a conflict is
    # reported, not applied. That keeps the source of record in charge, and
    # makes an override that has outlived its reason harmless rather than
    # masking. Filled before the subdivision is looked up, so the boundaries
    # map can place a port on its reviewed position.
    #
    # +fallback_coordinates+ is a list of such hashes, best first, for ports
    # neither of the above places (see Builder.fallback_coordinates). They rank
    # below the hand-written ones, and a generated row that has become
    # redundant is not reported: the next regeneration drops it.
    #
    # +alternate_names+ is a list of { locode => [names] }, best first (see
    # Builder.alternate_name_layers).
    def initialize(source, subdivisions: nil, boundaries: nil, overrides: {}, coordinate_overrides: {}, fallback_coordinates: [],
      alternate_names: [], rejected_names: {})
      @source = source
      @alternate_names = alternate_names
      @rejected_names = rejected_names
      @subdivisions = subdivisions
      @boundaries = boundaries
      @overrides = overrides
      @coordinate_overrides = coordinate_overrides
      @fallback_coordinates = fallback_coordinates
      @superseded = []
      @coordinates_superseded = []
    end

    # [locode, name, lat, lng, subdivision, principal_subdivision,
    # subdivision_path, subdivision_source, coordinate_source, alternate_names] per port, deduplicated and sorted
    # by locode. The path is the subdivision and everything above it, space
    # separated, most specific first (see Seaports::Subdivisions#path).
    # Sorted because the file is committed: a stable order means a refresh
    # diff shows what changed rather than the whole table moving.
    def rows
      @rows ||= begin
        rows = CSV.parse(@source, headers: true)
          .select { |row| seaport?(row) }
          .map { |row| port_row(row) }
          .uniq { |locode, *| locode }
          .sort_by(&:first)
        # The last cell is the port's candidate names until each has been
        # compared with the rest of its country.
        names = AlternateNames.resolve(rows.map { |locode, name, *, candidates| [locode, name, candidates] })
        rows.map { |row| [*row[0..-2], AlternateNames.dump(names.fetch(row.first, []))] }
      end
    end

    def write(path = Seaports::TABLE_PATH)
      CSV.open(path, "w") do |csv|
        csv << HEADERS
        rows.each { |row| csv << row }
      end
      path
    end

    def located_count
      rows.count { |row| !row[2].nil? }
    end

    def subdivided_count
      rows.count { |row| !row[5].nil? }
    end

    # Overrides worth a person's attention, written the way they should read
    # in a refresh pull request. An override wins over everything, so one that
    # has outlived its reason keeps masking better data until someone looks:
    #
    # - its port is no longer in UN/LOCODE's sea-port list;
    # - UN/LOCODE now gives the port a subdivision of its own;
    # - UN/LOCODE now gives the port a position of its own, which is the one
    #   shipped: the coordinate override is not applied and can go.
    def override_report
      rows # the report is a by-product of building them
      stale = (@overrides.keys - rows.map(&:first)).sort
        .map { |locode| "`#{locode}` is overridden but no longer a UN/LOCODE sea port: remove its row." }
      superseded = @superseded.uniq.sort.map do |locode, own, override|
        same = own == override ? "the same code" : "#{own}, not #{override}"
        "`#{locode}` now has a UN/LOCODE subdivision (#{same}): its override can go."
      end
      stale_points = (@coordinate_overrides.keys - rows.map(&:first)).sort.map do |locode|
        "`#{locode}` has a coordinate override but is no longer a UN/LOCODE sea port: remove its row."
      end
      superseded_points = @coordinates_superseded.uniq.sort.map do |locode, own, override|
        "`#{locode}` now has UN/LOCODE coordinates (#{own.join(', ')}, not #{override.join(', ')}): its coordinate override can go."
      end
      stale + superseded + stale_points + superseded_points
    end

    private

    # UNECE classifies every entry by function, and position 1 of that string
    # is "port" — the only one a vessel can call at. Keeping the other 98k
    # entries would mean a road terminal or a postal exchange could answer a
    # lookup for a ship's port call, which is worse than not answering at all.
    #
    # `Change` marks an entry's fate in the current release; "X" is one being
    # removed, and those are dropped.
    def seaport?(row)
      row["Function"].to_s.include?("1") &&
        !row["Change"].to_s.include?("X") &&
        !row["Location"].to_s.strip.empty? &&
        !row["Name"].to_s.strip.empty?
    end

    def port_row(row)
      locode = "#{row['Country']}#{row['Location']}".upcase
      lat, lng, coordinate_source = coordinates_for(locode, row)
      subdivision, source = subdivision_for(locode, row, lat, lng)
      path = @subdivisions&.path(subdivision) || []
      # A code whose chain breaks has no trustworthy top, so it is not kept.
      subdivision = source = nil if path.empty?
      name = row["Name"].strip
      alternates = AlternateNames.for(locode:, name:, located: !lat.nil?, layers: @alternate_names, rejected: @rejected_names)
      [locode, name, lat, lng, subdivision, path.last, path.empty? ? nil : path.join(" "), source, coordinate_source, alternates]
    end

    # [lat, lng, source] where source says whose position it is, so a later
    # step never has to guess from the values: UN/LOCODE's own when it has
    # one, else the reviewed override, else the first fallback dataset that
    # has one, else [nil, nil, nil].
    def coordinates_for(locode, row)
      own = decimal_degrees(row["Coordinates"])
      override = @coordinate_overrides[locode]
      unless own.first.nil?
        @coordinates_superseded << [locode, own, override] if override
        return [*own, "unlocode"]
      end
      return [*override, "override"] if override

      @fallback_coordinates.each_with_index do |points, index|
        return [*points[locode], FALLBACK_NAMES.fetch(index, "fallback")] if points[locode]
      end
      [nil, nil, nil]
    end

    # [code, source], or [nil, nil] when no source has a valid one.
    def subdivision_for(locode, row, lat, lng)
      return [nil, nil] if @subdivisions.nil?

      country = row["Country"].to_s.strip.upcase
      own = @subdivisions.code(country, row["Subdivision"])

      if (override = @overrides[locode])
        code = @subdivisions.code(country, override.delete_prefix("#{country}-"))
        raise ArgumentError, "#{locode}: override #{override} is not an ISO 3166-2 code of #{country}" if code.nil?

        @superseded << [locode, own, code] if own
        return [code, "override"]
      end

      return [own, "unlocode"] if own

      mapped = (@boundaries&.codes_at(country, lat, lng) || []).lazy
        .filter_map { |candidate| @subdivisions.code(country, candidate.delete_prefix("#{country}-")) }.first
      mapped ? [mapped, "boundaries"] : [nil, nil]
    end

    # UNECE writes coordinates as "2421N 11812E" — degrees and whole minutes,
    # zero-padded, no separator. Rounded to four places, which is metres: the
    # source only resolves to a minute (about a mile), and writing more digits
    # than that would dress a coarse figure up as a survey.
    def decimal_degrees(value)
      match = value.to_s.strip.match(/\A(\d{2})(\d{2})([NS])\s+(\d{3})(\d{2})([EW])\z/)
      return [nil, nil] if match.nil?

      lat = (match[1].to_i + (match[2].to_i / 60.0)) * (match[3] == "S" ? -1 : 1)
      lng = (match[4].to_i + (match[5].to_i / 60.0)) * (match[6] == "W" ? -1 : 1)
      [lat.round(4), lng.round(4)]
    end
  end
end
